create table if not exists task_event (
    id bigint generated by default as identity primary key,
    task_id bigint not null,
    type varchar(50) not null,
    status varchar(30) not null check (status in ('RUNNING', 'SUCCESS', 'FAILED', 'INFO')),
    title varchar(500) not null,
    detail varchar(5000),
    payload json,
    created_at timestamp(6) not null,
    constraint fk_task_event_task foreign key (task_id) references agent_task(id)
);

create table if not exists task_interaction (
    id bigint generated by default as identity primary key,
    task_id bigint not null,
    input_type varchar(40) not null check (
        input_type in (
            'TEXT', 'TEXTAREA', 'YES_NO', 'DATE', 'DATETIME', 'SELECT',
            'SINGLE_CHOICE', 'MULTI_CHOICE', 'CONFIRM', 'FORM'
        )
    ),
    status varchar(40) not null check (
        status in ('PENDING', 'ANSWERED', 'SKIPPED', 'UNKNOWN', 'CANCELED', 'EXPIRED')
    ),
    question clob not null,
    content clob,
    context_key varchar(80),
    required boolean not null,
    options json,
    placeholder varchar(500),
    default_value varchar(1000),
    fields json,
    actions json,
    answer_action varchar(30) check (answer_action in ('SUBMIT', 'SKIP', 'UNKNOWN', 'CANCEL')),
    answer_action_key varchar(80),
    answer_text clob,
    answer_values json,
    selected_values json,
    answer_hint varchar(1000),
    answered_at timestamp(6),
    created_at timestamp(6) not null,
    constraint fk_task_interaction_task foreign key (task_id) references agent_task(id)
);

create table if not exists task_runtime_context_value (
    id bigint generated by default as identity primary key,
    task_id bigint not null,
    context_key varchar(120) not null,
    context_value clob,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_task_runtime_context_value unique (task_id, context_key),
    constraint fk_task_runtime_context_task foreign key (task_id) references agent_task(id)
);

create table if not exists task_share (
    id bigint generated by default as identity primary key,
    share_code varchar(40) not null unique,
    task_id bigint not null,
    created_by_user_id bigint,
    password_hash varchar(500) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_task_share_task foreign key (task_id) references agent_task(id),
    constraint fk_task_share_creator foreign key (created_by_user_id) references workbench_user(id)
);

create table if not exists task_share_round (
    share_id bigint not null,
    task_id bigint not null,
    primary key (share_id, task_id),
    constraint fk_task_share_round_share foreign key (share_id) references task_share(id),
    constraint fk_task_share_round_task foreign key (task_id) references agent_task(id)
);

create table if not exists resource_catalog_item (
    id bigint generated by default as identity primary key,
    owner_user_id bigint not null,
    provider_code varchar(100) not null,
    provider_scope varchar(120) not null,
    source_config_id bigint,
    resource_ref varchar(300) not null,
    resource_kind varchar(100) not null,
    name varchar(300) not null,
    description varchar(2000),
    aliases json,
    labels json,
    relations json,
    search_text varchar(5000),
    revision varchar(200),
    source_task_id bigint,
    observed_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint uk_resource_catalog_item unique (
        owner_user_id, provider_code, provider_scope, resource_ref
    )
);

