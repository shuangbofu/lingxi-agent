    primary key (premise_id, scenario_code),
    constraint fk_premise_visible_scenario_premise
        foreign key (premise_id) references analysis_premise(id)
);

create table if not exists analysis_premise_user (
    premise_id bigint not null,
    user_id bigint not null,
    primary key (premise_id, user_id),
    constraint fk_premise_user_premise
        foreign key (premise_id) references analysis_premise(id)
);

create table if not exists capability_config (
