create table if not exists workbench_user (
    id bigint generated by default as identity primary key,
    username varchar(80) not null unique,
    display_name varchar(80) not null,
    avatar_url varchar(500),
    password_hash varchar(200) not null,
    monthly_token_limit bigint,
    daily_token_limit bigint,
    weekly_token_limit bigint,
    role enum ('ADMIN', 'USER') not null,
    enabled boolean not null,
    last_login_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null
);

create table if not exists agent_capability (
    code varchar(80) primary key,
    enabled boolean not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null
);

create table if not exists agent_scenario (
    code varchar(80) primary key,
    enabled boolean not null,
    user_visible boolean default true not null,
    sort_order integer not null,
    capabilities json not null,
    capability_commands json not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null
);

create table if not exists analysis_premise (
    id bigint generated by default as identity primary key,
    code varchar(80) unique,
    name varchar(120) not null,
    description varchar(500),
    prompt_text clob,
    context_values json,
    scenario_context_values json,
    enabled boolean not null,
    global_visible boolean not null,
    sort_order integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null
);

create table if not exists analysis_premise_visible_scenario (
    premise_id bigint not null,
