create table if not exists model_provider (
    id varchar(100) primary key,
    owner_user_id bigint,
    provider_type varchar(40) not null,
    name varchar(120) not null,
    base_url varchar(1000) not null,
    api_key varchar(2000) not null,
    instruction_prompt clob,
    max_concurrency integer,
    enabled boolean not null,
    sort_order integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_model_provider_owner
        foreign key (owner_user_id) references workbench_user(id)
);

create table if not exists model_profile (
    id varchar(100) primary key,
    owner_user_id bigint,
    provider_id varchar(100) not null,
    name varchar(120) not null,
    description varchar(500),
    model varchar(160) not null,
    protocol varchar(30) not null check (protocol in ('RESPONSES', 'CHAT_COMPLETIONS')),
    context_window_tokens integer not null,
    reasoning_effort varchar(50),
    instruction_prompt clob,
    max_concurrency integer,
    enabled boolean not null,
    sort_order integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_model_profile_owner
        foreign key (owner_user_id) references workbench_user(id),
    constraint fk_model_profile_provider
        foreign key (provider_id) references model_provider(id)
);

create table if not exists model_pricing_plan (
    id varchar(100) primary key,
    provider_id varchar(100) not null,
    model_profile_id varchar(100),
